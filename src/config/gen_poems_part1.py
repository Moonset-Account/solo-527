import json, os, sys

def expand(data):
    poems = []
    for d in data:
        lines = []
        for i, txt in enumerate(d["lt"]):
            chars = []
            n = len(txt)
            ts_line = d["ts"][i]
            ps_line = d["ps"][i]
            ts_line = (ts_line + 'a' * n)[:n]
            ps_line = (ps_line + 'a' * n)[:n]
            for j, ch in enumerate(txt):
                tone_char = ts_line[j]
                tone_val = 'ping' if tone_char == 'p' else 'ze' if tone_char == 'z' else 'any'
                obj = {"char": ch, "tone": tone_val, "isRhyme": False, "isKeyword": False}
                for ri, ci, rg in d["rh"]:
                    if ri == i and ci == j:
                        obj["isRhyme"] = True
                        obj["_rg"] = rg
                key = (i, j)
                if key in d["kw"]:
                    obj["isKeyword"] = True
                    obj["imagery"] = d["kw"][key]
                chars.append(obj)
            tp = [{"tone": "ping" if c == "p" else "ze" if c == "z" else "any", "expected": "平" if c == "p" else "仄" if c == "z" else "可平可仄"} for c in ps_line]
            lobj = {"text": txt, "characters": chars, "tonePattern": tp}
            rg_set = set()
            for ri, ci, rg in d["rh"]:
                if ri == i:
                    rg_set.add(rg)
            if rg_set:
                lobj["rhymeGroup"] = list(rg_set)[0]
            lines.append(lobj)
        poems.append({
            "id": d["id"], "title": d["t"], "author": d["a"], "dynasty": d["d"],
            "ciPaiId": d["cp"], "difficulty": d["df"], "imagery": d["im"], "lines": lines
        })
    return poems

