function generateTrackingPoints(orderId: string, riderId: string, count: number): TrackingPoint[] {
  const points: TrackingPoint[] = [];
  const baseLat = 39.9042;
  const baseLng = 116.4074;

  for (let i = 0; i < count; i++) {
    points.push({
      id: `tp-${orderId}-${i}`,
      orderId,
      riderId,
      lat: baseLat + (Math.random() - 0.5) * 0.05,
      lng: baseLng + (Math.random() - 0.5) * 0.05,
      speed: Math.random() * 30 + 10,
      timestamp: new Date(now.getTime() - (count - i) * 2 * 60 * 1000),
    });
  }
  return points;
}

