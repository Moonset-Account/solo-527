function generateTemperatureRecords(orderId: string, count: number, hasAnomaly: boolean = false): TemperatureRecord[] {
  const records: TemperatureRecord[] = [];

  for (let i = 0; i < count; i++) {
    let temp = 4 + Math.random() * 2;
    let isNormal = true;

    if (hasAnomaly && i > count / 2) {
      temp = 10 + Math.random() * 5;
      isNormal = false;
    }

    records.push({
      id: `tr-${orderId}-${i}`,
      orderId,
      temperature: parseFloat(temp.toFixed(1)),
      humidity: parseFloat((55 + Math.random() * 10).toFixed(1)),
      timestamp: new Date(now.getTime() - (count - i) * 5 * 60 * 1000),
      isNormal,
    });
  }
  return records;
}

