export function getTone(char) {
  if (TONE_MAP[char]) return TONE_MAP[char]
  const code = char.charCodeAt(0)
  if (code >= 0x4e00 && code <= 0x9fff) {
    const tone3 = getTone3(char)
    return (tone3 === '平') ? '平' : '仄'
  }
  return '中'
}

export function getTone3(char) {
  if (TONE_3_MAP[char]) return TONE_3_MAP[char]
  return '平'
}

export function analyzeTones(text) {
  const result = []
  for (const char of text) {
    if (/[\u4e00-\u9fa5]/.test(char)) {
      result.push({ char, tone: getTone(char), tone3: getTone3(char) })
    }
  }
  return result
}

export function checkTonePattern(text, pattern) {
  const tones = analyzeTones(text)
  if (tones.length !== pattern.length) return false
  for (let i = 0; i < pattern.length; i++) {
    const expected = pattern[i]
    const actual = tones[i].tone
    if (expected === '中') continue
    if (expected === '平' && actual !== '平') return false
    if (expected === '仄' && actual !== '仄' && actual !== '中') return false
  }
  return true
}

export function getToneDescription(tone) {
  const descriptions = {
    '平': '平声',
    '仄': '仄声',
    '上': '上声',
    '去': '去声',
    '入': '入声',
    '中': '可平可仄'
  }
  return descriptions[tone] || tone
}

export function getPatternViolations(text, pattern) {
  const tones = analyzeTones(text)
  const violations = []
  for (let i = 0; i < Math.min(tones.length, pattern.length); i++) {
    const expected = pattern[i]
    const actual = tones[i].tone
    if (expected !== '中') {
      if (expected === '平' && actual !== '平') {
        violations.push({ position: i, char: tones[i].char, expected, actual })
      } else if (expected === '仄' && actual === '平') {
        violations.push({ position: i, char: tones[i].char, expected, actual })
      }
    }
  }
  return violations
}
